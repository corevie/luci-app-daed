func parseSections(t *testing.T, content string) *Config {
	t.Helper()
	sections, err := config_parser.Parse(content)
	if err != nil {
		t.Fatalf("parse: %v", err)
	}
	conf, err := New(sections)
	if err != nil {
		t.Fatalf("New: %v", err)
	}
	return conf
}

func TestEchTunnelSectionAbsent(t *testing.T) {
	conf := parseSections(t, `global{} routing{}`)
	if conf.EchTunnel != nil {
		t.Fatalf("EchTunnel = %+v, want nil", conf.EchTunnel)
	}
	// Marshaling a config without the section must not emit it.
	b, err := conf.Marshal(2)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(b), "ech_tunnel") {
		t.Fatalf("marshal emitted ech_tunnel for nil section:\n%s", b)
	}
}

func TestEchTunnelSectionParse(t *testing.T) {
	conf := parseSections(t, `
global{}
routing{}
ech_tunnel {
    listen: '127.0.0.1:1080'
    server: 'your-worker.workers.dev:443/tunnel'
    ip: '104.21.16.1'
    token: 'secret-token'
    dns: 'dns.alidns.com/dns-query'
    ech_domain: 'cloudflare-ech.com'
}
`)
	want := &EchTunnel{
		Listen:    "127.0.0.1:1080",
		Server:    "your-worker.workers.dev:443/tunnel",
		ServerIP:  "104.21.16.1",
		Token:     "secret-token",
		DNSServer: "dns.alidns.com/dns-query",
		EchDomain: "cloudflare-ech.com",
	}
	if !reflect.DeepEqual(conf.EchTunnel, want) {
		t.Fatalf("EchTunnel = %+v, want %+v", conf.EchTunnel, want)
	}
}

func TestEchTunnelSectionServerRequired(t *testing.T) {
	sections, err := config_parser.Parse(`
global{}
routing{}
ech_tunnel {
    listen: '127.0.0.1:1080'
}
`)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := New(sections); err == nil {
		t.Fatal("expected error when ech_tunnel has no server")
	} else if !strings.Contains(err.Error(), "server") {
		t.Fatalf("error = %v, want server validation error", err)
	}
}

